#!/usr/bin/env node
/**
 * Bundles each Edge Function into a single self-contained TypeScript file.
 *
 * Supabase's Management API deploys one file per function, so the `_shared/*` helpers are inlined
 * here (dependency order, imports stripped, `export` keywords removed). The result is also what
 * `supabase functions deploy` uploads, which keeps local and API deployments identical.
 *
 *   node bundle.mjs            # writes dist/<function>.ts
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const sharedDir = join(root, '_shared');
const outDir = join(root, 'dist');
const distDir = join(root, 'dist-min');
const MINIFY = process.argv.includes('--minify');

const LOCAL_IMPORT = /^\s*import\s[^;]*from\s+['"]\.{1,2}\//;
const EXTERNAL_IMPORT = /^\s*import\s[^;]*from\s+['"](npm:|jsr:|https:)/;

/** Drops every import statement: local ones are inlined, external ones are hoisted to the header. */
const stripRelativeImports = (source) =>
  source
    .split('\n')
    .filter((line) => !LOCAL_IMPORT.test(line) && !EXTERNAL_IMPORT.test(line))
    .join('\n');

const stripExports = (source) =>
  source
    .replace(/^export\s+(async\s+function|function|const|let|class|interface|type|enum)\s/gm, '$1 ')
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '');

const npmImports = (source) =>
  source
    .split('\n')
    .filter((line) => /^\s*import\s[^;]*from\s+['"](npm:|jsr:|https:)/.test(line));

const collectShared = (file, seen = new Set(), order = []) => {
  const absolute = resolve(sharedDir, file);
  if (seen.has(absolute)) return order;
  seen.add(absolute);
  const source = readFileSync(absolute, 'utf8');
  for (const match of source.matchAll(/from\s+['"]\.\/([\w.-]+\.ts)['"]/g)) {
    collectShared(match[1], seen, order);
  }
  order.push({ absolute, source });
  return order;
};

const functions = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(root, entry.name, 'index.ts')))
  .map((entry) => entry.name)
  .sort();

mkdirSync(outDir, { recursive: true });
mkdirSync(distDir, { recursive: true });

/** Drops whole-line comments and blank lines: the payload the Management API receives. */
const compact = (source) =>
  source
    .split('\n')
    .filter((line) => line.trim().length > 0 && !/^\s*\/\//.test(line))
    .join('\n');

for (const name of functions) {
  const entry = join(root, name, 'index.ts');
  const body = readFileSync(entry, 'utf8');

  const sharedFiles = new Set();
  for (const match of body.matchAll(/from\s+['"]\.\.\/_shared\/([\w.-]+\.ts)['"]/g)) {
    sharedFiles.add(match[1]);
  }

  const ordered = [];
  const seen = new Set();
  for (const file of sharedFiles) collectShared(file, seen, ordered);

  const externalImports = new Set();
  for (const { source } of ordered) npmImports(source).forEach((line) => externalImports.add(line.trim()));
  npmImports(body).forEach((line) => externalImports.add(line.trim()));

  const sharedCode = ordered
    .map(({ absolute, source }) => {
      const relative = absolute.slice(sharedDir.length + 1);
      return `/* --- _shared/${relative} --- */\n${stripExports(stripRelativeImports(source)).trim()}`;
    })
    .join('\n\n');

  const bundled = [
    `// Generated by supabase/functions/bundle.mjs — do not edit. Source: ${name}/index.ts`,
    [...externalImports].join('\n'),
    '// deno-lint-ignore-file',
    'declare const Deno: { env: { get(name: string): string | undefined }; serve(handler: (req: Request) => Response | Promise<Response>): void };',
    sharedCode,
    `/* --- ${name}/index.ts --- */`,
    stripRelativeImports(body).trim(),
    '',
  ]
    .filter(Boolean)
    .join('\n\n');

  writeFileSync(join(outDir, `${name}.ts`), bundled);
  writeFileSync(join(distDir, `${name}.ts`), compact(bundled));
  const lines = compact(bundled).split('\n').length;
  console.log(`bundled ${name} (${bundled.split('\n').length} lines, ${lines} compacted)`);
}
